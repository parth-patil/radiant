function size() {
  const w = Math.max(320, Math.round(cards[0].st.clientWidth));
  const h = Math.round(w * 9 / 16);
  stage.w = w; stage.h = h;
  if (stage.renderer) stage.renderer.setSize(w, h, false);
  for (const c of cards) {
    c.canvas.width = Math.round(w * stage.dpr); c.canvas.height = Math.round(h * stage.dpr);
    if (c.inst) c.inst.onResize();
    c.dirty = true;
  }
}

function buildLabels(c) {
  c.labelsEl.textContent = '';
  c.labels = c.inst.labels.map((spec) => {
    const d = el('div', 'lb d' + Math.min(3, spec.depth));
    d.textContent = spec.text;
    d.style.color = spec.color;
    c.labelsEl.appendChild(d);
    return { spec, el: d };
  });
}

const v = new THREE.Vector3();
function placeLabels(c) {
  const inst = c.inst, cam = inst.camera;
  const f = stage.h / 2 / Math.tan(cam.fov * Math.PI / 360);
  for (const lb of c.labels) {
    v.copy(lb.spec.pos).applyMatrix4(inst.world.matrixWorld).applyMatrix4(cam.matrixWorldInverse);
    const depth = -v.z;
    if (depth < 0.5) { lb.el.style.opacity = '0'; continue; }
    const x = stage.w / 2 + v.x * f / depth, y = stage.h / 2 - v.y * f / depth;
    const s = f / depth / PPU * inst.labelScale;
    let op = smooth((inst.grow - lb.spec.len) / 0.8);
    if (inst.labelFade) op *= inst.labelFade(depth);
    lb.el.style.transform = 'translate(' + x.toFixed(1) + 'px,' + y.toFixed(1) + 'px) scale(' + s.toFixed(3) + ') translate(-50%,' + (lb.spec.valign === 'middle' ? '-50%' : '-100%') + ')';
    lb.op = op; lb.x = x; lb.y = y; lb.s = s; lb.depth = depth;
    if (!inst.declutter) lb.el.style.opacity = op.toFixed(2);
  }
  if (inst.declutter) {
    // Nearest and shallowest labels win; one that would cover an accepted label is hidden.
    const order = c.labels.filter((lb) => lb.op > 0.02).sort((a, b) => (a.spec.depth - b.spec.depth) * 2.2 + (a.depth - b.depth));
    const taken = [];
    for (const lb of c.labels) lb.show = false;
    for (const lb of order) {
      if (!lb.w) { lb.w = lb.el.offsetWidth; lb.h = lb.el.offsetHeight; }
      const w = lb.w * lb.s + 8, h = lb.h * lb.s + 6;
      const r = [lb.x - w / 2, lb.y - h / 2, lb.x + w / 2, lb.y + h / 2];
      if (taken.some((q) => r[0] < q[2] && r[2] > q[0] && r[1] < q[3] && r[3] > q[1])) continue;
      taken.push(r); lb.show = true;
    }
    for (const lb of c.labels) lb.el.style.opacity = lb.show ? lb.op.toFixed(2) : '0';
  }
}

// Drawing is on demand. A stage is drawn only when its picture changed (growth, a tilt in progress, or the
// stage in focus when it has flow, pulses or a turntable); nothing is drawn while the page is scrolling, and
// scenes are built ahead of time in idle moments so that scrolling to a new stage does not compile shaders.
let scrollUntil = 0;
window.addEventListener('scroll', () => { scrollUntil = performance.now() + 150; }, { passive: true });

function draw(c, t, focus, force) {
  try {
    if (!c.inst) { c.inst = c.def.make(); buildLabels(c); c.dirty = true; }
    const changed = c.inst.tick(t, c.ptr, focus);
    if (!changed && !c.dirty && !force) return;
    c.inst.render();
    c.ctx.drawImage(stage.renderer.domElement, 0, 0);
    placeLabels(c);
    c.dirty = false;
  } catch (e) {
    c.err = e;
    console.error(c.def.id, e);
    c.labelsEl.innerHTML = '<pre class="err">' + String(e && e.stack || e).replace(/</g, '&lt;') + '</pre>';
  }
}

function frame(ms) {
  requestAnimationFrame(frame);
  if (ms < scrollUntil) return;
  const t = ms / 1000;
  const mid = window.innerHeight / 2;
  let focus = null, best = 1e9;
  for (const c of cards) {
    if (!c.visible || c.err) continue;
    const r = c.st.getBoundingClientRect();
    const d = Math.abs((r.top + r.bottom) / 2 - mid);
    if (d < best) { best = d; focus = c; }
  }
  for (const c of cards) if (c.visible && !c.err) draw(c, t, c === focus, false);
}

function warm() {
  const next = cards.find((c) => !c.inst && !c.err);
  if (!next) return;
  const run = () => {
    if (performance.now() < scrollUntil + 250) { setTimeout(warm, 300); return; }
    if (!next.inst) {
      draw(next, performance.now() / 1000, false, true);
      if (next.inst && !next.seen) { next.inst.settle(); draw(next, performance.now() / 1000, false, true); }
    }
    setTimeout(warm, 120);
  };
  if (window.requestIdleCallback) window.requestIdleCallback(run, { timeout: 1500 }); else setTimeout(run, 200);
}

async function start() {
  await loadImages(window.__ASSETS);
  const w = Math.max(320, Math.round(cards[0].st.clientWidth));
  initStage(w, Math.round(w * 9 / 16));
  size();
  let timer = 0;
  window.addEventListener('resize', () => { clearTimeout(timer); timer = setTimeout(size, 120); });
  const io = new IntersectionObserver((entries) => { for (const e of entries) { const c = cards.find((k) => k.st === e.target); if (!c) continue; c.visible = e.isIntersecting; if (c.visible && !c.seen) { c.seen = true; c.dirty = true; if (c.inst) c.inst.replay(); } } }, { rootMargin: '40px' });
  cards.forEach((c) => io.observe(c.st));
  const spy = new IntersectionObserver((entries) => { for (const e of entries) if (e.isIntersecting) for (const a of nav.querySelectorAll('a')) a.classList.toggle('on', a.getAttribute('href') === '#' + e.target.id); }, { rootMargin: '-45% 0px -50% 0px' });
  cards.forEach((c) => spy.observe(c.sec));
  window.__gallery = { cards, stage };
  requestAnimationFrame(frame);
  setTimeout(warm, 600);
}
start().catch((e) => { console.error(e); document.getElementById('cards').prepend(el('pre', 'err', String(e && e.stack || e))); });
